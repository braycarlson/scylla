const codepoint_max: u32 = 0x10ffff;

comptime {
    assert(grapheme_runs[grapheme_runs.len - 1].prefix_sum > codepoint_max);

    for (grapheme_runs) |run| {
        assert(run.start < grapheme_offsets.len);
    }
}

pub fn is_printable(codepoint: u21) bool {
    assert(codepoint <= codepoint_max);

    const value: u32 = codepoint;

    if (value < 32) return false;
    if (value < 127) return true;

    if (value < 0x10000) return check(value, &singletons_0_upper, &singletons_0_lower, &normal_0);
    if (value < 0x20000) return check(value, &singletons_1_upper, &singletons_1_lower, &normal_1);

    for (unprintable_ranges) |range| {
        if (range[0] <= value) {
            if (value < range[1]) return false;
        }
    }

    return true;
}

pub fn is_grapheme_extended(codepoint: u21) bool {
    assert(codepoint <= codepoint_max);

    const needle: u32 = codepoint;

    if (needle <= 0x2ff) return false;
    return skip_search(needle);
}

fn check(codepoint: u32, uppers: []const [2]u8, lowers: []const u8, normal: []const u8) bool {
    assert(codepoint >= 127);
    assert(codepoint < 0x20000);
    assert(uppers.len > 0);
    assert(normal.len > 0);
    assert(lowers.len <= std.math.maxInt(u32));

    const value: u16 = @truncate(codepoint);
    const upper_wanted: u8 = @truncate(value >> 8);
    const lower_wanted: u8 = @truncate(value);
    var lower_start: usize = 0;

    for (uppers) |entry| {
        const lower_end = lower_start + entry[1];

        if (upper_wanted == entry[0]) {
            for (lowers[lower_start..lower_end]) |lower| {
                if (lower == lower_wanted) return false;
            }
        }

        if (upper_wanted < entry[0]) break;

        lower_start = lower_end;
    }

    assert(lower_start <= lowers.len);

    return normal_walk(codepoint, normal);
}

fn normal_walk(codepoint: u32, normal: []const u8) bool {
    assert(codepoint >= 127);
    assert(codepoint < 0x20000);
    assert(normal.len > 0);

    const value: u16 = @truncate(codepoint);
    var remaining: i32 = value;
    var current = true;
    var index: usize = 0;

    while (index < normal.len) : (index += 1) {
        const byte = normal[index];
        var length: i32 = byte;

        if (byte & 0x80 != 0) {
            index += 1;

            assert(index < normal.len);

            length = (@as(i32, byte & 0x7f) << 8) | normal[index];
        }

        remaining -= length;

        if (remaining < 0) break;

        current = !current;
    }

    return current;
}

fn skip_search(needle: u32) bool {
    assert(needle <= codepoint_max);

    var run_index: usize = 0;

    while (run_index < grapheme_runs.len) : (run_index += 1) {
        if (grapheme_runs[run_index].prefix_sum > needle) break;
    }

    assert(run_index < grapheme_runs.len);

    var offset_index: usize = grapheme_runs[run_index].start;

    const offset_end = if (run_index + 1 < grapheme_runs.len)
        grapheme_runs[run_index + 1].start
    else
        grapheme_offsets.len;

    const base = if (run_index > 0) grapheme_runs[run_index - 1].prefix_sum else 0;
    const total = needle - base;
    var prefix_sum: u32 = 0;

    for (0..offset_end - offset_index - 1) |_| {
        prefix_sum += grapheme_offsets[offset_index];

        if (prefix_sum > total) break;

        offset_index += 1;
    }

    return offset_index % 2 == 1;
}

