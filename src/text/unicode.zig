pub fn decode(source: []const u8, offset: u32) ?Scalar {
    assert(offset < source.len);

    if (source[offset] < 0x80) return .{ .value = source[offset], .width = 1 };

    const width = std.unicode.utf8ByteSequenceLength(source[offset]) catch return null;
    if (width > source.len - offset) return null;

    const bytes = source[offset..];

    const value = switch (width) {
        2 => std.unicode.utf8Decode2(bytes[0..2].*),
        3 => std.unicode.utf8Decode3(bytes[0..3].*),
        4 => std.unicode.utf8Decode4(bytes[0..4].*),
        else => unreachable,
    } catch return null;

    assert(value >= 0x80);
    assert(value <= scalar_max);
    assert(width <= width_max);

    return .{ .value = value, .width = width };
}

pub fn decode_before(source: []const u8, end: u32) ?Scalar {
    assert(end > 0);
    assert(end <= source.len);

    if (source[end - 1] < 0x80) return .{ .value = source[end - 1], .width = 1 };

    var lead = end - 1;

    for (0..width_max - 1) |_| {
        if (lead == 0) break;
        if (source[lead] & 0xc0 != 0x80) break;

        lead -= 1;
    }

    assert(lead < end);
    assert(end - lead <= width_max);

    if (source[lead] < 0x80) return null;

    const scalar = decode(source, lead) orelse return null;
    if (lead + scalar.width != end) return null;
    return scalar;
}

pub fn is_alphabetic(scalar: u21) bool {
    assert(scalar <= scalar_max);

    if (scalar < 0x80) return std.ascii.isAlphabetic(@intCast(scalar));
    return ranges_contain(&alphabetic_ranges, scalar);
}

pub fn is_alphanumeric(scalar: u21) bool {
    assert(scalar <= scalar_max);

    if (scalar < 0x80) return std.ascii.isAlphanumeric(@intCast(scalar));
    if (is_alphabetic(scalar)) return true;
    return ranges_contain(&numeric_ranges, scalar);
}

fn is_digit(scalar: u21) bool {
    assert(scalar >= 0x80);
    assert(scalar <= scalar_max);

    return ranges_contain(&digit_ranges, scalar);
}

pub fn is_id_continue(scalar: u21) bool {
    assert(scalar <= scalar_max);

    if (is_xid_continue(scalar)) return true;
    if (scalar < 0x80) return false;

    const result = ranges_contain(&id_continue_beyond_xid_ranges, scalar);

    if (is_id_start(scalar)) assert(result);

    return result;
}

pub fn is_id_start(scalar: u21) bool {
    assert(scalar <= scalar_max);

    if (is_xid_start(scalar)) return true;
    if (scalar < 0x80) return false;
    return ranges_contain(&id_start_beyond_xid_ranges, scalar);
}

pub fn is_line_terminator(scalar: u21) bool {
    assert(scalar <= scalar_max);

    if (scalar < 0x80) return scalar == '\n' or scalar == '\r';
    return scalar >= line_terminator_min and scalar <= line_terminator_max;
}

pub fn is_whitespace(scalar: u21) bool {
    assert(scalar <= scalar_max);

    if (scalar < 0x80) return std.ascii.isWhitespace(@intCast(scalar));
    return ranges_contain(&whitespace_ranges, scalar);
}

pub fn is_xid_continue(scalar: u21) bool {
    assert(scalar <= scalar_max);

    if (scalar < 0x80) {
        const byte: u8 = @intCast(scalar);
        return std.ascii.isAlphanumeric(byte) or byte == '_';
    }

    const result = ranges_contain(&xid_continue_ranges, scalar);

    if (is_xid_start(scalar)) assert(result);

    return result;
}

pub fn is_xid_start(scalar: u21) bool {
    assert(scalar <= scalar_max);

    if (scalar < 0x80) return std.ascii.isAlphabetic(@intCast(scalar));
    return ranges_contain(&xid_start_ranges, scalar);
}

fn ranges_contain(ranges: []const Range, scalar: u21) bool {
    assert(ranges.len > 0);
    assert(scalar <= 0x10FFFF);

    const index = std.sort.partitionPoint(Range, ranges, scalar, Range.ends_before);

    assert(index <= ranges.len);

    if (index == ranges.len) return false;

    assert(ranges[index].last >= scalar);

    return ranges[index].first <= scalar;
}

fn ranges_valid(ranges: []const Range) bool {
    assert(ranges.len > 0);

    var floor: u21 = 0x80;

    for (ranges) |range| {
        if (range.first < floor) return false;
        if (range.last < range.first) return false;
        if (range.last > scalar_max) return false;

        floor = range.last + 2;
    }

    return true;
}

