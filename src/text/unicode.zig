test "a scalar decodes only where its bytes are whole and well formed" {
    const expect = std.testing.expectEqual;

    try expect(Scalar{ .value = 0xe4, .width = 2 }, decode("\xc3\xa4", 0).?);
    try expect(Scalar{ .value = 0x2639, .width = 3 }, decode("\xe2\x98\xb9", 0).?);
    try expect(Scalar{ .value = 0x1f600, .width = 4 }, decode("\xf0\x9f\x98\x80", 0).?);
    try expect(null, decode("\xc3", 0));
    try expect(null, decode("\xe2\x98", 0));
    try expect(null, decode("\xc0\x80", 0));
    try expect(null, decode("\xe0\x80\x80", 0));
    try expect(null, decode("\xed\xa0\x80", 0));
    try expect(null, decode("\xf0\x80\x80\x80", 0));
    try expect(null, decode("\xf4\x90\x80\x80", 0));
    try expect(null, decode("\x80", 0));
    try expect(null, decode("\xff", 0));
}

